async def _apply_visual_quality_gate(task: BuildTask, content: str) -> tuple[bool, list[dict]]:
    """Apply visual quality gate for FRONTEND artifacts. Returns (passed, findings)."""
    if task.kind != TaskKind.FRONTEND:
        return True, []
    
    result = audit_frontend(content)
    return result["passed"], result["findings"]


async def execute_task(task: BuildTask, spec: ProjectSpec) -> BuildArtifact:
    artifact_id = str(uuid.uuid4())
    created_at = datetime.now(timezone.utc).isoformat()
    
    if task.kind == TaskKind.FRONTEND:
        system_prompt = (
            "Kamu Agus, Frontend Engineer RakitDigital. "
            "Buat kode React/Next.js yang bersih, modular, dan production-ready. "
            "Output HANYA kode tanpa penjelasan tambahan."
        )
        user_message = f"Buat frontend untuk: {task.title}. Fitur: {spec.features}. Klien: {spec.client_name}"
        content = await call_llm(AGUS_MODEL, system_prompt, user_message)
        if not content or "MOCK MODE ACTIVE" in content:
            content = _mock_frontend(task, spec)
        filename = f"{task.title.lower().replace(' ', '_')}.tsx"
        
    elif task.kind == TaskKind.BACKEND:
        system_prompt = (
            "Kamu Bambang, Backend Engineer RakitDigital. "
            "Buat kode FastAPI/Python yang bersih, modular, dan production-ready. "
            "Output HANYA kode tanpa penjelasan tambahan."
        )
        user_message = f"Buat backend untuk: {task.title}. Fitur: {spec.features}. Klien: {spec.client_name}"
        content = await call_llm(BAMBANG_MODEL, system_prompt, user_message)
        if not content or "MOCK MODE ACTIVE" in content:
            content = _mock_backend(task, spec)
        filename = f"{task.title.lower().replace(' ', '_')}.py"
        
    elif task.kind == TaskKind.DATABASE:
        system_prompt = (
            "Kamu Dedi, Database Engineer RakitDigital. "
            "Buat schema SQL/PostgreSQL yang bersih, normalized, dan production-ready. "
            "Output HANYA SQL tanpa penjelasan tambahan."
        )
        user_message = f"Buat schema database untuk: {task.title}. Fitur: {spec.features}. Klien: {spec.client_name}"
        content = await call_llm(DEDI_MODEL, system_prompt, user_message)
        if not content or "MOCK MODE ACTIVE" in content:
            content = _mock_database(task, spec)
        filename = f"{task.title.lower().replace(' ', '_')}.sql"
    
    # Apply visual quality gate for FRONTEND
    passed, findings = await _apply_visual_quality_gate(task, content)
    if not passed:
        # Mark task as FAILED so it triggers rework
        task.status = TaskStatus.FAILED
        await save_build_task(task)
        
        # Create rework task with findings
        rework_task = BuildTask(
            task_id=str(uuid.uuid4()),
            project_id=task.project_id,
            kind=TaskKind.FRONTEND,
            title=f"Rework: Visual Quality Gate - {task.title}",
            status=TaskStatus.PENDING,
        )
        await save_build_task(rework_task)
        
        # Return artifact with findings in content for traceability
        content = f"// VISUAL QUALITY GATE FAILED\n// Findings: {findings}\n\n{content}"
        
        artifact = BuildArtifact(
            artifact_id=artifact_id,
            project_id=task.project_id,
            task_id=task.task_id,
            filename=filename,
            content=content,
            created_at=created_at,
        )
        
        await save_build_artifact(artifact)
        
        # Task remains FAILED - do NOT mark as DONE
        await save_build_task(task)
        
        return artifact
    
    artifact = BuildArtifact(
        artifact_id=artifact_id,
        project_id=task.project_id,
        task_id=task.task_id,
        filename=filename,
        content=content,
        created_at=created_at,
    )
    
    await save_build_artifact(artifact)
    
    task.status = TaskStatus.DONE
    task.artifact_id = artifact_id
    await save_build_task(task)
    
    return artifact


def breakdown_tasks(spec: ProjectSpec) -> list[BuildTask]:
    tasks = []
    
    for feature in spec.features:
        feature_slug = feature.lower().replace(' ', '_')
        
        task_frontend = BuildTask(
            task_id=str(uuid.uuid4()),
            project_id="",  # Will be set by caller
            kind=TaskKind.FRONTEND,
            title=f"Frontend: {feature}",
            status=TaskStatus.PENDING,
        )
        
        task_backend = BuildTask(
            task_id=str(uuid.uuid4()),
            project_id="",
            kind=TaskKind.BACKEND,
            title=f"Backend: {feature}",
            status=TaskStatus.PENDING,
        )
        
        task_database = BuildTask(
            task_id=str(uuid.uuid4()),
            project_id="",
            kind=TaskKind.DATABASE,
            title=f"Database: {feature}",
            status=TaskStatus.PENDING,
        )
        
        tasks.extend([task_frontend, task_backend, task_database])
    
    return tasks


async def run_build(project_id: str) -> BuildSubmission:
    project = await get_project(project_id)
    if project is None:
        raise ValueError("Project not found")
    
    if not project.get("spec_json"):
        raise ValueError("Project spec not found")

    spec = ProjectSpec.model_validate_json(project["spec_json"])

    tasks = await list_build_tasks(project_id)

    if not tasks:
        tasks = breakdown_tasks(spec)
        for task in tasks:
            task.project_id = project_id
            await save_build_task(task)
        tasks = await list_build_tasks(project_id)
    
    await update_project_state(project_id, "BUILDING")
    
    completed_artifacts = []
    
    for task in tasks:
        if task.status == TaskStatus.DONE:
            if task.artifact_id:
                artifact = await get_build_artifact(task.artifact_id)
                if artifact:
                    completed_artifacts.append(artifact.artifact_id)
            continue
        
        max_attempts = 3
        success = False
        
        while task.attempts < max_attempts and not success:
            task.attempts += 1
            await save_build_task(task)
            
            try:
                artifact = await execute_task(task, spec)
                completed_artifacts.append(artifact.artifact_id)
                success = True
            except Exception as e:
                if task.attempts >= max_attempts:
                    task.status = TaskStatus.FAILED
                    await save_build_task(task)
                    await update_project_state(project_id, "BLOCKED")
                    
                    failed_tasks = [t for t in tasks if t.status == TaskStatus.FAILED]
                    return BuildSubmission(
                        submission_id=str(uuid.uuid4()),
                        project_id=project_id,
                        artifact_ids=completed_artifacts,
                        task_count=len(tasks),
                        created_at=datetime.now(timezone.utc).isoformat(),
                        status=f"BLOCKED: Task {task.task_id} ({task.title}) failed after {max_attempts} attempts"
                    )
                continue
    
    all_done = all(t.status == TaskStatus.DONE for t in tasks)
    
    if all_done:
        await update_project_state(project_id, "AUDITING")
        
        submission = BuildSubmission(
            submission_id=str(uuid.uuid4()),
            project_id=project_id,
            artifact_ids=completed_artifacts,
            task_count=len(tasks),
            created_at=datetime.now(timezone.utc).isoformat(),
            status="READY_FOR_AUDIT"
        )
        
        await save_build_submission(submission)
        return submission
    else:
        return BuildSubmission(
            submission_id=str(uuid.uuid4()),
            project_id=project_id,
            artifact_ids=completed_artifacts,
            task_count=len(tasks),
            created_at=datetime.now(timezone.utc).isoformat(),
            status="PARTIAL"
        )


async def get_build_status(project_id: str) -> dict:
    project = await get_project(project_id)
    if project is None:
        raise ValueError("Project not found")
    
    tasks = await list_build_tasks(project_id)
    
    pending = sum(1 for t in tasks if t.status == TaskStatus.PENDING)
    done = sum(1 for t in tasks if t.status == TaskStatus.DONE)
    failed = sum(1 for t in tasks if t.status == TaskStatus.FAILED)
    
    return {
        "project_id": project_id,
        "project_state": project["state"],
        "total_tasks": len(tasks),
        "pending": pending,
        "done": done,
        "failed": failed,
        "tasks": [
            {
                "task_id": t.task_id,
                "kind": t.kind.value,
                "title": t.title,
                "status": t.status.value,
                "attempts": t.attempts,
                "artifact_id": t.artifact_id,
            }
            for t in tasks
        ],
    }